"""
Run with: python main_flow.py

Pipeline:
    fetch candles (Groww or dummy) -> compute indicators -> rule-based signal -> LLM explains it

The LLM step is the ONLY place a model is involved, and its job is to explain/summarize
the already-computed signal in plain English -- it does not decide the signal itself.
"""

from dotenv import load_dotenv
from litellm import completion
from crewai.flow.flow import Flow, listen, start

import config
from data_provider import get_provider
from indicators import compute_all
from strategy import generate_signal

load_dotenv()


class SignalFlow(Flow):
    model = config.LLM_MODEL

    @start()
    def fetch_and_analyze(self):
        provider = get_provider()
        results = {}

        for symbol_key in config.SYMBOLS:
            df = provider.get_candles(symbol_key)
            df = compute_all(df)
            signal = generate_signal(df)
            results[symbol_key] = signal
            print(f"\n[{symbol_key}] signal={signal['signal']} score={signal['score']} "
                  f"close={signal['close']}")
            for r in signal["reasons"]:
                print(f"   - {r}")

        self.state["results"] = results
        return results

    @listen(fetch_and_analyze)
    def explain_signals(self, results):
        summary_lines = []
        for symbol_key, signal in results.items():
            summary_lines.append(
                f"{symbol_key}: signal={signal['signal']}, score={signal['score']}, "
                f"close={signal['close']}, RSI={signal['rsi']}, "
                f"VWAP_dev%={signal['vwap_dev_pct']}, reasons={signal['reasons']}"
            )
        summary_text = "\n".join(summary_lines)

        prompt = f"""You are explaining rule-based technical trading signals to a trader.
The signals below were generated by fixed technical rules (EMA crossover, RSI, VWAP
deviation) -- you are NOT deciding or second-guessing the signal, only explaining it
clearly and flagging anything that looks contradictory or worth double-checking.

Signals:
{summary_text}

Write a short, plain-English summary (a few sentences per instrument). Note explicitly
that this is not financial advice and the rules should be backtested before being traded on.
"""

        response = completion(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
        )
        explanation = response["choices"][0]["message"]["content"]
        self.state["explanation"] = explanation
        return explanation


if __name__ == "__main__":
    flow = SignalFlow()
    result = flow.kickoff()
    print("\n=== LLM Explanation ===\n")
    print(result)
